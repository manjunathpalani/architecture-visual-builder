import type { ArchitectureDocument, Integration, SystemNode } from '../types'
import type { DrawingElement } from '../types/diagram'

function stamp(doc: ArchitectureDocument): ArchitectureDocument {
  return {
    ...doc,
    metadata: {
      ...doc.metadata,
      updatedAt: new Date().toISOString(),
    },
  }
}

function zoneRect(
  id: string,
  x: number,
  y: number,
  w: number,
  h: number,
  color: string,
): DrawingElement {
  return {
    id,
    type: 'rectangle',
    points: [
      { x, y },
      { x: x + w, y: y + h },
    ],
    color,
    strokeWidth: 2,
    fill: `${color}12`,
  }
}

function zoneLabel(id: string, x: number, y: number, text: string, color: string): DrawingElement {
  return {
    id,
    type: 'text',
    points: [{ x, y }],
    color,
    strokeWidth: 1,
    text,
    fontSize: 13,
  }
}

function edge(
  id: string,
  source: string,
  target: string,
  label: string,
  protocol: Integration['protocol'] = 'REST API',
  frequency: Integration['frequency'] = 'near-real-time',
  extra?: Partial<Integration>,
): Integration {
  return {
    id,
    source,
    target,
    label,
    direction: extra?.direction ?? 'bidirectional',
    protocol,
    frequency,
    dataFormat: extra?.dataFormat ?? 'JSON',
    description: extra?.description ?? label,
    ...extra,
  }
}

