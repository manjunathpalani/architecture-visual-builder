export const AZURE_SERVICE_FAMILY: Record<string, AzureIconFamily> = {}

const V = 'Microsoft Azure'

function az(
  category: string,
  label: string,
  service: string,
  family: AzureIconFamily,
  extras?: Record<string, string>,
): PaletteItem {
  AZURE_SERVICE_FAMILY[service] = family
  return {
    type: 'azure',
    label,
    category,
    defaultProperties: { vendor: V, service, iconFamily: family, ...extras },
  }
}

function zone(label: string, zoneName: string, size?: { width: number; height: number }): PaletteItem {
  return {
    type: 'group',
    label,
    category: 'Azure Groups',
    flowType: 'group',
    defaultProperties: { vendor: V, service: label, zone: zoneName, color: '#0078d4' },
    defaultSize: size ?? { width: 320, height: 200 },
  }
}

